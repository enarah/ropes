import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";

test("TrueNAS sandbox builds and starts compiled Next without database mutations or development transport", () => {
  const dockerfile = readFileSync("Dockerfile", "utf8");
  const compose = readFileSync("docker-compose.demo.yml", "utf8");
  const scripts = JSON.parse(readFileSync("package.json", "utf8")).scripts;
  assert.equal(scripts.start, "next start");
  assert.equal(scripts.prestart, undefined);
  assert.equal(scripts.poststart, undefined);
  const appSection = compose.split("  ropes: &demo-app")[1]?.split("  migrate:")[0];
  const databaseSection = compose.split("  postgres:")[1]?.split("  ropes:")[0];
  assert.ok(appSection);
  assert.ok(databaseSection);
  assert.match(dockerfile, /FROM node:26[^\s]* AS demo/);
  assert.match(dockerfile, /RUN npm ci/);
  assert.match(dockerfile, /apt-get install -y --no-install-recommends openssl ca-certificates/);
  assert.ok(dockerfile.indexOf("npm ci") < dockerfile.indexOf("npm run db:generate"));
  assert.ok(dockerfile.indexOf("npm run db:generate") < dockerfile.indexOf("npm run build"));
  assert.match(dockerfile, /ENV NODE_ENV=production/);
  assert.match(dockerfile, /USER node/);
  const command = JSON.parse(dockerfile.match(/^CMD (.+)$/m)![1]);
  assert.deepEqual(command, ["npm", "run", "start", "--", "--hostname", "0.0.0.0", "--port", "3000"]);
  assert.doesNotMatch(dockerfile, /npm.+run.+dev|db:(?:seed|deploy|migrate)|tracking:demo:load/);
  assert.match(appSection, /image: \$\{ROPES_DEMO_IMAGE:/);
  assert.match(appSection, /target: demo/);
  assert.match(appSection, /NODE_ENV: production/);
  assert.match(appSection, /ROPES_RUNTIME_ENV: sandbox/);
  assert.match(appSection, /ROPES_DEMO_MODE: "true"/);
  assert.doesNotMatch(appSection, /NODE_ENV: development|db:(?:seed|deploy)|tracking:demo:load|ALLOW_DESTRUCTIVE|ALLOW_SYNTHETIC/);
  assert.match(compose, /image: postgres:16\b/);
  assert.doesNotMatch(databaseSection, /ports:|published:|network_mode:.*host/);
  assert.match(appSection, /\/api\/health/);
  assert.match(compose, /profiles: \["tools"\]/);
  assert.match(compose, /command: \["npm", "run", "db:deploy"\]/);
  assert.match(compose, /command: \["npm", "run", "db:seed"\]/);
  const seedSection = compose.split("  seed:")[1];
  assert.match(seedSection, /NODE_ENV: development/);
  assert.match(seedSection, /ALLOW_DESTRUCTIVE_DEMO_SEED: "true"/);
  assert.match(compose, /DESTRUCTIVE — DISPOSABLE DEMO DATABASE ONLY/);
  const prismaConfig = readFileSync("prisma.config.ts", "utf8");
  assert.match(prismaConfig, /seed: "node --import tsx prisma\/seed.ts"/);
  const seedSource = readFileSync("prisma/seed.ts", "utf8");
  assert.match(seedSource, /ALLOW_DESTRUCTIVE_DEMO_SEED/);
  assert.match(seedSource, /databaseName !== "ropes_demo"/);
  assert.match(seedSource, /NODE_ENV"\] === "production"/);
  const loaderSource = readFileSync("lib/tracking/demo-loader.ts", "utf8");
  assert.match(loaderSource, /env\.NODE_ENV === "production"/);
  assert.doesNotMatch(compose + dockerfile, /argus\.enarah|GOOGLE_CLIENT_SECRET|NEXTAUTH_SECRET/i);
});
